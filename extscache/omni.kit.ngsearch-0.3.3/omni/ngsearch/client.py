class Search:
    def __init__(self, transport: Client):
        self.transport = transport

    async def __aenter__(self) -> "Search":
        await self.transport.prepare()
        return self

    async def __aexit__(self, exc_type, exc_val, exc_tb):
        await self.transport.close()

    async def find(self, query: SearchQuery, token: str) -> AsyncIterator[Path]:
        """
        Asynchronous generator function that returns Paths to assets in Nucleus
        (with metadata) that matching the search query.

        @param {ClientVersion} version version of the client that is being
        connected to the service (populated automatically)
        @param {SearchQuery} query search terms, tag list (not used), and
        parent folder of search.
        @param {string} token user authentication token that is used for
        verification of user access for each returned asset path
        @returns assets in Nucleus that best match the input query (in the
        generator fashion).

        @example
        Sample function usage from the python autogenerated client.
        ```
        >>> res: Path
        >>> async for res in client.find(
        >>>     query={"parent": "/", "query": '"magical spoon"'}, token=<user
        access token>
        >>> ):
        >>>     ...
        ```
        """
        _request = {}
        _request["version"] = SearchFindClientVersion
        _request["query"] = query
        _request["token"] = token
        agen = self.transport.call_many("Search", "find", _request, request_type=SearchFindArgs, return_type=Path)
        try:
            async for _response in agen:
                yield _response
        finally:
            await agen.aclose()

