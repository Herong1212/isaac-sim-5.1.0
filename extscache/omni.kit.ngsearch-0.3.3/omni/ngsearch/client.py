    async def search(
        self,
        query: Optional[str] = None,
        n: Optional[float] = None,
        filter_repeating: Optional[bool] = None,
        filter_by_path: Optional[str] = None,
        filter_by_ext: Optional[List[str]] = None,
        kw_must: Optional[List[str]] = None,
        kw_must_not: Optional[List[str]] = None,
        return_predictions: Optional[bool] = None,
        return_images: Optional[bool] = None,
        return_embeddings: Optional[bool] = None,
        similarity_threshold: Optional[float] = None,
        search_config: Optional[SearchConfig] = None,
        scroll: Optional[bool] = None,
        token: Optional[str] = None,
        only_key: Optional[bool] = None,
    ) -> Results:
        """
        Asynchronous function to search for assets in Nucleus given an input
        query. Together with asset paths it is able to return additional
        information (e.g. previews of assets, from which embeddings were
        generated, predictions for the embeddings and embeddings themselves).

        This function returns all the assets that it find in a single message,
        which can be limited, depending on the transport that the service is
        using (e.g. websockets, http).

        @param {string} query Input text query that can be text or base64
        encoded image
        @param {number} n Number of paths that need to be returned (if set to
        -1 will return all the paths)
        @param {string} filter_by_path path by which the response should be
        filtered (default: None)
        @param {string[]} filter_by_ext filter by path extension (default: None)
        @param {string[]} kw_must must include keyword (default: None)
        @param {string[]} kw_must_not must not include keyword (default: None)
        @param {boolean} return_predictions if true - additional return
        prediction (default: false)
        @param {boolean} return_images if true - additional return images
        (default: false)
        @param {boolean} return_embeddings if true - return embeddings
        (default: false)
        @param {number} similarity_threshold filter out similar results
        (default: 0.0)
        @param {string} token user authentication token
        @param {boolean} only_key if true - optimize the processing to request
        minimal information from ES. In this case return_images and
        return_embedding options are unavailable (default: false)
        @returns assets from Nucleus that best describe the input query (all
        the results are returned in a single message).

        @example
        Sample function usage from the python autogenerated client.
        ```
        >>> first_batch = await client.search(
        >>>     "sample query",
        >>>     filter_by_path="/",
        >>>     search_config=SearchConfig(method=SearchMethod.exact)
        >>> )
        ```
        """
        _request = {}
        if query is not None:
            _request["query"] = query
        if n is not None:
            _request["n"] = n
        if filter_repeating is not None:
            _request["filter_repeating"] = filter_repeating
        if filter_by_path is not None:
            _request["filter_by_path"] = filter_by_path
        if filter_by_ext is not None:
            _request["filter_by_ext"] = filter_by_ext
        if kw_must is not None:
            _request["kw_must"] = kw_must
        if kw_must_not is not None:
            _request["kw_must_not"] = kw_must_not
        if return_predictions is not None:
            _request["return_predictions"] = return_predictions
        if return_images is not None:
            _request["return_images"] = return_images
        if return_embeddings is not None:
            _request["return_embeddings"] = return_embeddings
        if similarity_threshold is not None:
            _request["similarity_threshold"] = similarity_threshold
        if search_config is not None:
            _request["search_config"] = search_config
        if scroll is not None:
            _request["scroll"] = scroll
        if token is not None:
            _request["token"] = token
        if only_key is not None:
            _request["only_key"] = only_key
        _response = await self.transport.call(
            "NGSearchService", "search", _request, request_type=NgsearchServiceSearchArgs, return_type=Results
        )
        return _response

    async def scroll(self, scroll_id: str, n: Optional[float] = None) -> Results:
        """
        Asynchronous function that allows doing pagination of results and
        continue retrieving items for the same input query when the search was
        already executed.

        @param {string} scroll_id ID of the search that was already executed
        @param {number} n Number of paths that need to be returned (if set to
        -1 will return all the paths)
        @returns more results for a given search request instance (all the
        results a returned in a single message)

        @example
        Sample function usage from the python autogenerated client.
        ```
        >>> first_batch = await client.search("sample query", scroll=True)
        >>> second_batch = await client.scroll(first_batch.scroll_id)
        ```
        """
        _request = {}
        _request["scroll_id"] = scroll_id
        if n is not None:
            _request["n"] = n
        _response = await self.transport.call(
            "NGSearchService", "scroll", _request, request_type=NgsearchServiceScrollArgs, return_type=Results
        )
        return _response

