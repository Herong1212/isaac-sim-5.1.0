    async def test_augmentation_sobel_edges(self):
        """Test raises error from failed sobel edges augmentation"""
        anno_normals = rep.annotators.get("normals", device="cuda").augment("ColorizeNormals").augment("Sobel")
        anno_normals.attach(self.rp)
        anno_segmentation = rep.annotators.get("semantic_segmentation", device="cuda", init_params={"colorize": True})
        # anno_segmentation = anno_segmentation.augment("sobel_edges")  # TODO: fix issue setting init params to augmented annotator
        anno_segmentation.attach(self.rp)

        await rep.orchestrator.step_async()
        data_normals = anno_normals.get_data()
        data_segmentation_in = anno_segmentation.get_data()["data"]
        data_segmentation = wp.empty_like(data_segmentation_in)
        wp.launch(
            rep.augmentations_default.sobel_edges,
            dim=data_normals.shape[:2],
            inputs=[data_segmentation_in, data_segmentation],
            device=data_segmentation_in.device,
        )
        self.assertEqual(len(data_normals.shape), 3)
        self.assertEqual(len(data_segmentation.shape), 3)

        golden_file_path_normals = os.path.join(self.golden_dir, "aug_sobel_edges_normals.png")
        golden_file_path_segmentation = os.path.join(self.golden_dir, "aug_sobel_edges_segmentation.png")
        golden_image_normals = np.asarray(Image.open(golden_file_path_normals))
        golden_image_segmentation = np.asarray(Image.open(golden_file_path_segmentation))

        std_dev_normals = np.sqrt(np.square(data_normals.numpy() - golden_image_normals).astype(float).mean())
        if std_dev_normals > 2:
            if omni.kit.test.utils.is_running_in_teamcity():
                tc_output_image_comparison(
                    "aug_sobel_edges_normals", golden_file_path_normals, self.out_dir, data_normals.numpy()
                )
            if omni.kit.test.utils.is_running_in_gitlab():
                gitlab_output_image_comparison(
                    "test_augmentation_sobel_edges_normals", golden_file_path_normals, image_data=data_normals.numpy()
                )
        self.assertLess(std_dev_normals, 2)

        std_dev_segmentation = np.sqrt(
            np.square(data_segmentation.numpy() - golden_image_segmentation).astype(float).mean()
        )
        if std_dev_segmentation > 2:
            if omni.kit.test.utils.is_running_in_teamcity():
                tc_output_image_comparison(
                    "aug_sobel_edges_segmentation",
                    golden_file_path_segmentation,
                    self.out_dir,
                    data_segmentation.numpy(),
                )
            if omni.kit.test.utils.is_running_in_gitlab():
                gitlab_output_image_comparison(
                    "test_augmentation_sobel_edges_segmentation",
                    golden_file_path_segmentation,
                    image_data=data_segmentation.numpy(),
                )
        self.assertLess(std_dev_segmentation, 2)

