    async def test_augmentation_depth(self):
        @wp.kernel
        def gaussian_noise_depth_wp(
            data_in: wp.array2d(dtype=wp.float32), data_out: wp.array2d(dtype=wp.float32), sigma: float, seed: int
        ):
            i, j = wp.tid()
            state = wp.rand_init(seed, wp.tid())
            data_out[i, j] = data_in[i, j] + sigma * wp.randn(state)

        rep.annotators.register_augmentation(
            "depth_noise", rep.annotators.Augmentation.from_function(gaussian_noise_depth_wp, sigma=0.01, seed=None)
        )

        anno = rep.annotators.get("distance_to_camera")
        anno.augment("depth_noise")
        anno.attach(self.rp)

        await rep.orchestrator.step_async()

        data = anno.get_data()

        self.assertEqual(type(data), wp.array)
        self.assertEqual(data.shape, (480, 640))
        self.assertTrue(
            all([v > 0.0 for v in data.numpy().reshape([-1])]),
            f"One or more output values were not updated: {data.numpy()}",
        )

    async def test_augmentation_gpu_dtype_change(self):
        # GPU depth colorize kernel
        @wp.kernel
        def colorize_depth(
            data_in: wp.array2d(dtype=wp.float32), data_out: wp.array2d(dtype=wp.uint8), z_far: float = 100.0
        ):
            i, j = wp.tid()
            data_out[i, j] = wp.uint8((1.0 - (min(z_far, data_in[i, j]) / z_far)) * 255.0)

        anno = rep.annotators.get("distance_to_camera").augment(colorize_depth)
        anno.attach(self.rp)
        await rep.orchestrator.step_async()
        data = anno.get_data()

        self.assertEqual(data.shape, (480, 640))
        self.assertEqual(data.dtype, wp.uint8)

    async def test_augmentation_cpu_dtype_change(self):
        # CPU noise kernel
        def image_gaussian_noise_np(data_in: np.ndarray, seed, sigma: float = 25.0):
            np.random.seed(seed)
            return data_in + sigma * np.random.randn(*data_in.shape)

        def to_uint32(data_in: np.ndarray):
            data_in = np.nan_to_num(data_in, posinf=10000)
            return data_in.astype(np.int32)

        anno = rep.annotators.get("distance_to_camera").augment(image_gaussian_noise_np, seed=1234)
        anno.attach(self.rp)
        await rep.orchestrator.step_async()
        data = anno.get_data()

        self.assertEqual(data.shape, (480, 640))
        self.assertEqual(data.dtype, np.float64)

        anno = anno.augment(to_uint32)
        await rep.orchestrator.step_async()
        data = anno.get_data()

        self.assertEqual(data.shape, (480, 640))
        self.assertEqual(data.dtype, np.int32)

