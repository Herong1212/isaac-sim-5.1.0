# ==============================================================================================================
class FileType(Enum):
    """Enum enumerating the different files accessed by the node generator.
    User Files:
    - CPP -> C++ file, OgnMyNode.cpp, lives in same directory as the .ogn file
    - CU -> Cuda file, OgnMyNode.cu, lives in same directory as the .ogn file
    - OGN -> .ogn node definition file, usually in the source tree and symlinked to in the build tree
    - PYTHON -> python file, OgnMyNode.py, lives in same directory as the .ogn file

    Generated Files:
    - CPP_DB -> cpp header database, OgnMyNodeDatabase.h, lives in the include/ subdir of the ogn generated files dir
    - DOCS -> documentation, lives in docs/ subdir of the ogn generated files dir
    - PYTHON_DB -> python database, OgnMyNodeDatabase.py, lives in the ogn generated files dir
    - TEST -> test script, TestOgnMyNode.py, lives in the tests/ subdir of the ogn generated files dir
    - USD -> USD template, OgnMyNodeTemplate.usda, lives in the tests/usd/ subdir of the ogn generated files dir
    """

    CPP = auto()
    CPP_DB = auto()
    CU = auto()
    DOCS = auto()
    ICON = auto()
    OGN = auto()
    PYTHON = auto()
    PYTHON_DB = auto()
    TEST = auto()
    USD = auto()

    @classmethod
    def all_in_pattern_order(cls) -> list[FileType]:
        """Returns the list of file type enums in order of how their file name patterns should be matched.
        The ordering is important because some patterns match more than one prefix/suffix combination so the
        most restrictive need to go first."""
        return [cls.TEST, cls.USD, cls.OGN, cls.DOCS, cls.CU, cls.CPP_DB, cls.CPP, cls.ICON, cls.PYTHON_DB, cls.PYTHON]


# ==============================================================================================================
def is_user_file_type(file_type: FileType) -> bool:
    """Return True iff the given file type is to a file written by the user, not generated"""
    return file_type in [FileType.OGN, FileType.CPP, FileType.CU, FileType.PYTHON]


# ==============================================================================================================
def is_generated_file_type(file_type: FileType) -> bool:
    """Return True iff the given file type is to a file generated by the code"""
    return file_type in [FileType.DOCS, FileType.ICON, FileType.USD, FileType.TEST, FileType.CPP_DB, FileType.PYTHON_DB]


