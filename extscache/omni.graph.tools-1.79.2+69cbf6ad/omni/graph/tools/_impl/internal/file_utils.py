def load_module_from_file(new_module_name: str, python_file_path: Path) -> ModuleType:
    """Loads a Python module directly from a file, installs it into the module space, and returns the new module"""
    _ = LOG.disabled or LOG.info("Importing module %s from %s", new_module_name, python_file_path)
    if python_file_path.is_dir():
        # There's no guarantee the directory is a module or a package in its own right so the safest thing to do
        # is to find some arbitrary file and import it to populate the namespace
        for path_object in python_file_path.rglob("*.py"):
            if path_object.is_file():
                relative_location = ".".join(path_object.relative_to(python_file_path).with_suffix("").parts)
                return load_module_from_file(f"{new_module_name}.{relative_location}", path_object)
        _ = LOG.disabled or LOG.info("--> No Python files in the directory. No module returned.")
        return None

    # Not sure if things like .pyc will work but no reason to outright exclude them
    if not python_file_path.suffix.startswith(".py"):
        _ = LOG.disabled or LOG.info("--> Not a Python file. No module returned.")
        return None

    module = None
    spec = spec_from_file_location(new_module_name, str(python_file_path))
    if spec is None:
        _ = LOG.disabled or LOG.error("--> Could not create spec. Asserting an error.")
        raise ImportError(f"Could not load spec for module '{new_module_name}' at: {python_file_path}")
    module = module_from_spec(spec)
    sys.modules[new_module_name] = module
    try:
        spec.loader.exec_module(module)
    except FileNotFoundError as error:
        raise ImportError(f"{error.strerror}: {python_file_path}") from error
    _ = LOG.disabled or LOG.info("... created the module as %s", module)
    return module


