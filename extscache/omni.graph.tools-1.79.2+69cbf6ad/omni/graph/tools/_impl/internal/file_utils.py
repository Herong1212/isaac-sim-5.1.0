def walk_with_excludes(start: Path, exclude: set(str)) -> tuple(str, list[str], list[str]):
    """Same usage as os.walk:
    Crawl the directory tree from the start, yields a 3 tuple for itself and each subdirectory,
    except don't follow symlinks to paths already searched, and don't search directories excluded by name

    Args:
        start: Path to some directory to crawl, presumably the extension root.
        exclude: Set of directory names to exclude from the walk

    Returns:
        dirpath, dirnames, filenames
    """
    _ = LOG.disabled or LOG.info("_walk_with_excludes(start=%s, exclude=%s)", start, exclude)

    followed_targets = set()  # to exclude redundant symlinks

    def __dir_is_excluded_or_redundant(start, subdir_name):
        if subdir_name in exclude:
            return True
        subdir_path = Path(start) / subdir_name
        target = str(subdir_path.resolve())
        if target in followed_targets:
            return True
        followed_targets.add(target)
        return False

    for root, subdirs, filenames in os.walk(start, topdown=True, followlinks=True):
        subdirs[:] = [d for d in subdirs if not __dir_is_excluded_or_redundant(root, d)]
        _ = LOG.disabled or LOG.info("   ... walked %s, %s, %s", Path(root).as_posix(), subdirs, filenames)
        yield (Path(root).as_posix(), subdirs, filenames)


# ==============================================================================================================
def find_ogn_build_directory(current_path: Path) -> Path | None:
    """Walk up from the current_path and find the _build/ogn/ directory in the build tree above it.
    Returns None if the directory could not be found
    """
    # _build is the root in a local build, dev is the root in an installed build
    if current_path.name in ["_build", "dev"]:
        test_path = current_path / "ogn"
        if test_path.is_dir():
            return test_path
    parent_path = current_path.parent
    if parent_path != current_path:
        return find_ogn_build_directory(parent_path)
    return None


