# ==============================================================================================================
def get_ogn_file_name(node_type_name: str, ogn_file_type: FileType) -> str:
    """Get the full file name expected for the given file type on the given node type
    Args:
        node_type_name: Name of the node for which the filename is to be retrieved
        ogn_file_type: Type of file for which the filename is to be retrieved
    Returns:
        Name of the given file type on the given node type
    """
    return _FILE_PREFIXES[ogn_file_type] + node_type_name + _FILE_SUFFIXES[ogn_file_type]


# ==============================================================================================================
def get_ogn_type_and_node(filename: str) -> tuple(str, FileType):
    """Figure out what type of ogn-related file is passed in and what the name of the source node type is
    Args:
        filename: Name of the file to parse
    Returns:
        (Root node type name of the file, Type of File filename was) - Nones if the pattern was not recognized
    """
    for ogn_file_type in FileType.all_in_pattern_order():
        prefix = _FILE_PREFIXES.get(ogn_file_type, "")
        suffix = _FILE_SUFFIXES.get(ogn_file_type, "")
        if filename.startswith(prefix) and filename.endswith(suffix):
            node_type_name = filename[len(prefix) : (-len(suffix)) if suffix else None]
            return node_type_name, ogn_file_type
    return None, None


