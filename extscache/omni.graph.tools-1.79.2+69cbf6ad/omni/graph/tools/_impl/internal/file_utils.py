def get_module_path(module_to_check: ModuleType) -> Path | None:
    """Returns the path from which the module was generated, either file or directory, None if it could not be found"""
    path_to_module = None
    try:
        file_attribute = module_to_check.__file__
        path_to_module = Path(file_attribute)
    except (AttributeError, TypeError):
        try:
            if isinstance(module_to_check.__path__, list):
                file_attribute = module_to_check.__path__[0]  # pylint: disable=protected-access
            else:
                file_attribute = module_to_check.__path__._path[0]  # pylint: disable=protected-access
            path_to_module = Path(file_attribute)
        except (AttributeError, IndexError, TypeError):
            return None
    return path_to_module
