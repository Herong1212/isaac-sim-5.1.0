class OgnScanner:
    """Scan the ogn folders for nodes and tests"""

    def __init__(self, extension: ExtensionContentsV118, ogn_directory):
        self.ogn_directory = ogn_directory
        self.extension = extension
        self.other_files_found = defaultdict(list)  # Dictionary of ClassName: list of (file path, file type) to process
        self.has_tests = False

    @carb.profiler.profile
    def process_directory(self, entry: tuple):
        """Collect the file names with the associated class names and file types from the given root path."""
        root, dirs, file_names = entry
        root_path = Path(root)
        if root != self.ogn_directory:
            for ogn_subdir in dirs:
                if ogn_subdir != "tests":
                    _ = LOG.disabled or LOG.info("....Adding scanned directory %s/%s", root, ogn_subdir)
                    self.extension.ogn_subdirectories.append(root_path / ogn_subdir)

        result = []
        for file_name in file_names:
            file_path = root_path / file_name
            (class_name, file_type) = get_ogn_type_and_node(file_path.name)

            if file_type is None:
                continue

            # self.other_files_found[class_name].append((file_path, file_type))
            result.append((class_name, file_path, file_type))
        return result

    @carb.profiler.profile
    def add_files(self, entries, start, end):
        """Add the files that are discovered to each node definition."""
        for i in range(start, end):
            class_name, definition = entries[i]
            definition.add_files(
                self.other_files_found[class_name], self.extension._built_versions  # noqa: protected-access
            )

    @carb.profiler.profile
    def add_file_types(self, entries: list, start, end):
        """Create the NodeTypeDefinitions for each discovered node class."""
        file_type = FileType.OGN
        for i in range(start, end):
            class_name, file_path = entries[i]
            # Register this file name in the first pass to establish file names that represent node types
            if class_name in self.extension.node_type_definitions:
                # This can happen in old builds where the build has created both nodes/ and a linked ogn/nodes/
                # directory. They are identical so they can be ignored. An identical size is a good enough
                # confirmation that this is the case.
                file_size = file_path.stat().st_size
                try:
                    old_size = self.extension.node_type_definitions[class_name].file_path(file_type).stat().st_size
                except TypeError:
                    old_size = 0
                if old_size != file_size:
                    carb.log_warn(
                        f"Multiple .ogn files found for class '{class_name}'\n"
                        f"  Using {self.extension.node_type_definitions[class_name]}, ignoring {file_path}@{file_size}"
                    )
                continue
            _ = LOG.disabled or LOG.info("...constructing node type definition for %s at %s", class_name, file_path)
            self.extension.node_type_definitions[class_name] = NodeTypeDefinition(class_name, file_path)

    def run_processing(self):
        """Walk the extension paths to discover the nodes and tests."""
        file_types = []
        with ThreadPoolExecutor() as executor:
            for results in executor.map(
                self.process_directory, walk_with_excludes(self.ogn_directory, ["__pycache__"])
            ):
                for class_name, file_path, file_type in results:
                    # This information is needed at import time. Track it now to avoid a traversal to find it later.
                    if file_type == FileType.TEST:
                        self.has_tests = True

                    if file_type == FileType.OGN:
                        file_types.append((class_name, file_path))
                        continue

                    if (
                        file_type in (FileType.PYTHON_DB, FileType.CPP_DB)
                        and not self.extension._built_versions.has_version()  # noqa: protected-access
                    ):
                        # All database files should give the same version information since this is part of a build tree
                        # so choosing the first one to be representative is good enough. If that's not true then the fault
                        # is with the build and should not be corrected here.
                        self.extension._built_versions.set_versions_from_database(file_path)  # noqa: protected-access
                        _ = LOG.disabled or LOG.info(
                            "...extracted db versions %s from %s (%s)",
                            self.extension._built_versions,  # noqa: protected-access
                            file_path,
                            self.extension._built_versions.has_version(),  # noqa: protected-access
                        )

                    _ = LOG.disabled or LOG.info("...found file of type %s - %s", file_type, file_path)
                    self.other_files_found[class_name].append((file_path, file_type))

        # Try to add all of the build-related files to the node type definition
        futures = []
        thread_count = 32

        with ThreadPoolExecutor(thread_count) as executor:
            file_type_count = len(file_types)
            for start in range(0, file_type_count, thread_count):
                futures.append(
                    executor.submit(self.add_file_types, file_types, start, min(file_type_count, start + thread_count))
                )
        wait(futures, timeout=None, return_when=ALL_COMPLETED)

        with ThreadPoolExecutor(thread_count) as executor:
            defs = list(self.extension.node_type_definitions.items())
            def_count = len(defs)
            for start in range(0, def_count, thread_count):
                futures.append(executor.submit(self.add_files, defs, start, min(def_count, start + thread_count)))
        wait(futures, timeout=None, return_when=ALL_COMPLETED)


