def _scan_for_decorated_objects(source: str, file_path: str) -> tuple[Iterable, Iterable]:  # pragma: no cover
    """
    Scans a python file and extracts all objects with decorators.

    Args:
        source: Contents of the file to be scanned
        file_path: Corresponding path to file source (important for AST).

    Returns:
        tuple[Iterable, Iterable]: Tuple consisting of the list of decorated free function descriptors and the list of
            class descriptors. The free function descriptors are fixed key dictionaries consisting of:
                **name**: *The name of the function*
                **decorators**: *The unpacked list of decorators on the function*
                **return_annotation**: *The unpacked return type of the function*
                **parameters**: *The unpacked list of arguments to the function, both positional and keyword*
                **docstring**: *The docstring of the function**
            The class descriptions are also fixed key dictionaries consisting of:
                **name**: *The name of the function*
                **decorators**: *The unpacked list of decorators on the function*
                **functions**: *The unpacked list of functions in the class*
                **members**: *The unpacked list of class variables*
                **docstring**: *The docstring of the class as a whole**
    """
    _logger.info("Scanning for decorated objects %d lines from %s", source.count("\n") + 1, file_path)

    tree = ast.parse(source, filename=file_path)
    functions = (func for func in ast.walk(tree) if isinstance(func, (ast.FunctionDef, ast.AsyncFunctionDef)))
    parsed_funcs = []

    for function in functions:
        if not function.decorator_list:
            continue
        decorators = _unpack_decorators(function.decorator_list)
        arglist = _unpack_args(function.args)
        out_sig = _unpack_type_annotation(function.returns)
        out = {
            "name": function.name,
            "decorators": decorators,
            "return_annotation": out_sig,
            "parameters": arglist,
            "docstring": ast.get_docstring(function),
        }
        parsed_funcs.append(out)

    classes = (class_def for class_def in ast.walk(tree) if isinstance(class_def, ast.ClassDef))
    parsed_classes = []

    for class_def in classes:
        if not class_def.decorator_list:
            continue
        decorators = _unpack_decorators(class_def.decorator_list)
        functions = _unpack_classdef_functions(class_def)
        members = _unpack_classdef_members(class_def)
        out = {
            "name": class_def.name,
            "decorators": decorators,
            "functions": functions,
            "members": members,
            "docstring": ast.get_docstring(class_def),
        }
        parsed_classes.append(out)

    _logger.debug("Scanned functions --> %s", parsed_funcs)
    _logger.debug("Scanned classes --> %s", parsed_classes)
    return parsed_funcs, parsed_classes


