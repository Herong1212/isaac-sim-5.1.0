def _unpack_args(arglist: ast.arguments) -> dict:  # pragma: no cover    Unsupported code
    """Unpack a list of arguments from the AST into a dictionary of contents

    Args:
        arglist: Argument list from the AST to unpack

    Returns:
        dict: Dictionary whose keys are the argument names and whose values are the unpacked annotations of the
            argument types. e.g. the return from the arg list (a:float, b:str) would be {"a": "float", "b": "str"}
    """
    _logger.info("Unpacking argument list %s", arglist)
    _logger.debug("AST --> %s", ast.dump(arglist, indent=2))
    if arglist.vararg:
        raise ValueError(f"Specifying **args not supported in argument list {arglist.vararg}")
    if arglist.kwarg:
        raise ValueError(f"Specifying **kwargs not supported in argument list {arglist.kwarg}")
    out = {}
    for arg in arglist.posonlyargs + arglist.args + arglist.kwonlyargs:
        annotation = NO_ANNOTATION
        if arg.annotation:
            annotation = _unpack_type_annotation(arg.annotation)
        out[arg.arg] = annotation
    _logger.debug("Unpacked Args --> %s", out)
    return out


