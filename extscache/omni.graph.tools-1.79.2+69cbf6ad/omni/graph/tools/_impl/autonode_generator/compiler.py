def _unpack_classdef_functions(class_def: ast.ClassDef) -> Iterable:  # pragma: no cover    Unsupported code
    """Unpack the functions from a class definition from the AST

    Args:
        class_def: Class definition from the AST

    Returns:
        Iterable: A list of dictionaries containing the unpacked definitions for all functions in the class. The
            dictionaries will each contain three elements:
            **name**: *The name of the function*
            **arguments**: *The unpacked list of the arguments to the function (see _unpack_args())*
            **return_annotation**: *The unpacked definition of the return value type (see _unpack_annotation())*
    """
    _logger.info("Unpacking functons from class %s", class_def)
    _logger.debug("AST --> %s", ast.dump(class_def, indent=2))

    functions = (function for function in class_def.body if isinstance(function, ast.FunctionDef))
    ret = []
    for function in functions:
        if function.name.startswith(PRIVATE_MEMBER_PREFIX):
            continue
        arglist = _unpack_args(function.args)
        out_sig = _unpack_type_annotation(function.returns)
        out = {"arguments": arglist, "name": function.name, "return_annotation": out_sig}

        ret.append(out)

    _logger.debug("Unpacked Class Functions --> %s", ret)
    return ret


# --------------------------------------------------------------------------------------------------------------
def _unpack_classdef_members(class_def: ast.ClassDef) -> Iterable:  # pragma: no cover    Unsupported code
    """Unpack the class-level members of a class definition from the AST

    Args:
        class_def: Class definition from the AST

    Returns:
        Iterable: List of dictionaries with the unpacked description of all class member variables that are not
            explicitly marked as internal via the dunder ("__") prefix. The dictionary members will be:
            **name**: *Name of the class variable*
            **annotation**: *Unpacked annotation of that variable (see _unpack_annotation())*
    """
    _logger.info("Unpacking members from class %s", class_def)
    _logger.debug("AST --> %s", ast.dump(class_def, indent=2))

    variables = (variable for variable in class_def.body if isinstance(variable, ast.AnnAssign))
    ret = []
    for variable in variables:
        if not isinstance(variable.target, ast.Name):
            raise NotImplementedError(type(variable.target))
        if variable.target.id.startswith(PRIVATE_MEMBER_PREFIX):
            continue
        annotation = _unpack_type_annotation(variable.annotation)
        value = _unpack_type_annotation(variable.value)
        out = {"name": variable.target.id, "annotation": annotation, "value": value}
        ret.append(out)

    _logger.debug("Unpacked Class Members --> %s", ret)
    return ret


