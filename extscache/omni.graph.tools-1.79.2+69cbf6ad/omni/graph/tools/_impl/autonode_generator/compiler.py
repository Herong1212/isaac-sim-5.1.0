def _unpack_decorators(decorators: Iterable) -> list[any]:  # pragma: no cover    Unsupported code
    """Unpacks a list of decorators from the AST

    Args:
        decorators: Iterable list of decorators from the AST

    Returns:
        list[any]: List of unpacked elements from the decorators, as dictionaries and restricted to a few types
            Name: A simple named decorator, e.g. "@property"
            Call: A named decorator with arguments, e.g. "@deprecated('Do not use this')"
            Subscript: A named decorator with subscripts, e.g. "@grab_x_y_z[2]"
    """
    _logger.info("Unpacking decorators %s", decorators)
    _logger.debug("AST --> %s", "\n".join([ast.dump(decorator, indent=2) for decorator in decorators]))
    out = []
    for a_decorator in decorators:
        # Simple named decorator
        if isinstance(a_decorator, (ast.Name, ast.Attribute)):
            out.append({"name": _unpack_type_annotation(a_decorator)})

        # This is a decorator that has a function call in it
        elif isinstance(a_decorator, ast.Call):
            call = _unpack_call(a_decorator)
            out.append({"name": call["name"], "arguments": call["call_args"], "keywords": call["call_kws"]})

        # Decorator with subscripts in it
        elif isinstance(a_decorator, ast.Subscript):
            subscript = _unpack_subscript_type(a_decorator)
            out.append(subscript)

    _logger.debug("Unpacked Decorators --> %s", out)
    return out


