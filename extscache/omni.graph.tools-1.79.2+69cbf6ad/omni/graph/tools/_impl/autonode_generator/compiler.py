def _unpack_expression(arg: ast.Expression):  # pragma: no cover    Unsupported code
    """Unpack a single argument that is an expression (element without an assigment)

    Args:
        arg: Expression from the AST

    Returns:
        any: Constant value of the expression (e.g. "5", "x")

    Raises:
        ValueError: If the expression was not a constant (e.g. "a or b")
    """
    _logger.info("Unpacking expression %s", arg)
    if isinstance(arg, ast.Constant):
        return arg.value

    with suppress(AttributeError):
        if isinstance(arg.body, ast.Constant):
            return arg.body.value

    err = "Only constant values are supported"
    _logger.error(err)
    raise ValueError(err)


