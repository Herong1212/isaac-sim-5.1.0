def _generate_autonode_calls(
    source: str, file_path: str | None, module_name: str, module_relative: str, out_folder: str = None
) -> Iterable[tuple[str, str, str]]:  # pragma: no cover    Unsupported code
    """
    Generates .ogn and .py implementation files from a source file.

    Args:
        source: Source code to scan
        file_path: File path corresponding with the location of source. None means it is a plain string.
        module_name: Name of the python module being parsed
        module_relative: Relative path from the python module's root to this file.
        out_folder: Folder to which all .py and .ogn files get written. By default it's a subfolder of the module root.
           None means that the generated code should be returned rather than written out to the folder.

    Returns:
        Iterable[tuple[str, str,str]]: A list of class name,.ogn,.py for each generated node type implementation. If
        the out_folder was None then the .ogn/.py values will be the generated code as strings, otherwise they will be
        the paths to the generated files containing that code.
    """
    _logger.info(
        "Generating AutoNode calls from %d lines, file=%s, module=%s, relative=%s, out=%s",
        source.count("\n") + 1,
        file_path,
        module_name,
        module_relative,
        out_folder,
    )
    destination = _CodeDestination(file_path, out_folder)
    funcs, _ = _scan_for_decorated_objects(source, file_path=destination.file_path)

    for func in funcs:
        # Find the AutoNode decorators
        autonode_decorator = None
        for decorator in func["decorators"]:
            if decorator["name"].split(".")[-1] in AUTONODE_TOKENS_ALL:
                autonode_decorator = decorator
                break

        if not autonode_decorator:
            _logger.info("No AutoNode decorators found on %s, skipping it", func["name"])
            continue

        _logger.info("Found AutoNode annotation %s on %s", autonode_decorator["name"], func["name"])
        _name = func["name"]
        keywords = autonode_decorator.get("keywords", {})
        _add_execution_pins = keywords.get("add_execution_pins", False)

        full_module_name = module_relative if module_relative else module_name
        _unique_name = f"{full_module_name}.{func['name']}"

        _ui_name = keywords.get("ui_name", f"{python_name_to_ui_name(_name)} (AutoNode)") or _unique_name
        # Sanitize
        _file_name = as_class_name(_name)

        _tags = []
        wrapper = NodeTypeFromFunctionScan(
            func_descriptor=None,
            func_name=_name,
            func_signature=func,
            func_docstring=func.get("docstring", ""),
            add_execution_pins=_add_execution_pins,
            ui_name=_ui_name,
            unique_name=_unique_name,
            module_name=full_module_name,
            tags=_tags,
        )

        destination.add_code(_file_name, wrapper.get_ogn(), wrapper.get_node_impl_source())

    return destination.results


