class AutoNodeGenerator:  # pragma: no cover    Unsupported code
    """
    Entry point to parsing all AutoNode Python files in a single module.

    Parameters:
        module_name: The module name as described in an omniverse `extension.toml` file under `python.module`.
        python_root: The corresponding root folder where the python path begins for the module name
        import_paths: List of paths to the files being imported
        node_folder: The folder where the ogn nodes should be saved to. Defaults to `python_root` if not provided.
    """

    def __init__(self, module_name: str, python_root: str, import_paths: list[Path], node_folder: str | None):
        """Initialize the generator class for AutoNode definitions
        Args:
            module_name: The module name as described in an omniverse `extension.toml` file under `python.module`.
            python_root: The corresponding root folder where the python path begins for the module name
            import_paths: List of paths to the files being imported
            node_folder: The folder where the ogn nodes should be saved to. Defaults to `python_root` if not provided.
        """
        self.module_name = module_name
        self.python_root = Path(python_root)
        self.import_paths = import_paths
        self.node_folder = Path(node_folder or python_root)
        _logger.info(
            "AutoNode generation on module %s from files %s into node folder %s", module_name, import_paths, node_folder
        )

    # --------------------------------------------------------------------------------------------------------------
    def parse_all(self) -> Iterable[tuple[str, str, str]]:
        """Run the parser on every AutoNode definition in this module

        Returns:
            Iterable[tuple[str, str,str]]: A list of class name,.ogn,.py for each generated node type implementation.
            If the out_folder was None then the .ogn/.py values will be the generated code as strings, otherwise they
            will be the paths to the generated files containing that code.
        """
        # Scan once before parsing. This will prevent ambiguity on filesystem changes.
        # os.walk is used instead of Path.iterdir because it is faster.
        files_to_parse = []
        for import_path in self.import_paths:
            relative_import = import_path.relative_to(self.python_root)

            # Don't parse generated files
            if OGN_AUTOGENERATED_SUBFOLDER_NAME in relative_import.parts:
                _logger.debug("Skipping autogenerated subfolder %s", relative_import)
                continue

            if ".." in relative_import.parts:
                _logger.error(
                    "Module path '%s' is not relative to the given Python root directory '%s' - skipping.",
                    import_path,
                    self.python_root,
                )
                continue

            if relative_import.suffix == ".py":
                module_relative = f"{'.'.join(relative_import.parts[:-1])}.{relative_import.stem}"
                _logger.debug("...Adding (%s, %s)", relative_import, module_relative)
                files_to_parse.append((import_path, module_relative))

        # parse files from list
        generated_files = []

        # TODO: Potentially data parallel
        for file_path, module_relative in files_to_parse:
            _logger.info("Generating AutoNode Calls for %s as %s", file_path, module_relative)

            try:
                with ThreadsafeOpen(file_path, "r") as sourcefile:
                    source = sourcefile.read()
            except OSError as error:
                _logger.error("Unable to parse file at %s: %s", file_path, error)
                raise error

            extracted_call_files = _generate_autonode_calls(
                source,
                file_path=file_path,
                module_name=self.module_name,
                module_relative=module_relative,
                out_folder=self.node_folder,
            )
            generated_files += extracted_call_files

        return generated_files
