class _CodeDestination:  # pragma: no cover    Unsupported code
    """Helper class that handles the different paths required for output to file versus output via strings"""

    def __init__(self, _file_path: str | None, _out_folder: str | None):
        """Set up the code path information
        Args:
            _file_path: Location containing the AutoNode definition, or "<string>" if it came directly from a string
            _out_folder: Directory to write the generated code, or None if the code is to be returned as strings
        """
        if _file_path is None:
            # Generating code from a bare string (only for testing)
            self._file_path = "<string>"
            self._out_folder = _out_folder
        else:
            self._file_path = Path(_file_path)
            self._out_folder = self._file_path.parent if _out_folder is None else _out_folder
        if self._out_folder is not None:
            self._out_folder = Path(self._out_folder) / OGN_AUTOGENERATED_SUBFOLDER_NAME
        self._results = []
        _logger.info("Code destination of %s set to %s", self._file_path, self._out_folder)

    @property
    def file_path(self) -> str:
        """Returns:
        The location of the file that contained the AutoNode definition, or "<string>" if it generated from a string
        """
        return self._file_path

    @property
    def results(self) -> Iterable[tuple[str, str, str]]:
        """Get the code generation results
        Returns:
            List of generated code information. The first element of the tuple will always be the name of the class
            implementing the node type. If there was no output folder specified the next two elements will contain
            the generated .ogn and .py code as strings for the node type implementation, otherwise they will contain
            the paths to the .ogn and .py files containing that generated code.
        """
        return self._results

    def _add_code_as_string(self, class_file_name: str, ogn_code: str, python_code: str):
        """Add the generated code to the dictionary of string results"""
        _logger.info("Adding code string definition for %s", class_file_name)
        self._results.append((class_file_name, ogn_code, python_code))

    def _add_code_as_files(self, class_file_name: str, ogn_code: str, python_code: str):
        """Add the generated code to the folders and append the new file names to the results"""
        ogn_filepath = (self._out_folder / class_file_name).with_suffix(".ogn")
        py_filepath = (self._out_folder / class_file_name).with_suffix(".py")
        _logger.info("Adding .ogn/.py as %s", ogn_filepath)

        try:
            # Create the generated ogn folder for all modules in this subfolder
            if not self._out_folder.is_dir():
                self._out_folder.mkdir(mode=777, parents=True, exist_ok=False)
            with ThreadsafeOpen(ogn_filepath, "w") as f:
                f.write(ogn_code)
            _logger.info("Generated ogn: %s", ogn_filepath)
            with ThreadsafeOpen(py_filepath, "w") as f:
                f.write(python_code)
            _logger.info("Generated implementation: %s", py_filepath)

            self._results.append((class_file_name, ogn_filepath, py_filepath))

        except OSError as error:
            _logger.error("Operation failed when trying to write files: %s, %s: %s", ogn_filepath, py_filepath, error)
            raise error

    def add_code(self, class_file_name: str, ogn_code: str, python_code: str):
        """Add the generated code to the results, writing to the folder if provided"""
        if self._out_folder is None:
            self._add_code_as_string(class_file_name, ogn_code, python_code)
        else:
            self._add_code_as_files(class_file_name, ogn_code, python_code)


