# ==============================================================================================================
class _SubscriptDict(TypedDict):
    """Return type when unpacking an ast.Subscript object"""

    value: any
    """Subscripted object name"""
    contents: any
    """Subscript constant or slice values"""


# ==============================================================================================================
class _CallDict(TypedDict):
    """Return type when unpacking an ast.Call object"""

    name: str
    """Name of the function"""
    call_args: list
    """List of unpacked positional arguments"""
    call_kws: dict
    """Dictionary of unpacked keyword arguments"""


