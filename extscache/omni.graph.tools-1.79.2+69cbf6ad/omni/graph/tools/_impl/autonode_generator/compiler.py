# Unpackers
def _unpack_type_annotation(
    annotation: ast.Name | ast.Constant | ast.Subscript | ast.Tuple | ast.BinOp | ast.Attribute,
) -> str | dict:  # pragma: no cover    Unsupported code
    """Unpack a type annotation on a value from its AST description

    This is what is returned from the various legal types of annotation:

        ast.Name -> A string representing the annotation type type (e.g. a:str -> "str")
        ast.Constant -> A string with the constant value in it (e.g. a:str -> "4")
        ast.Subscript -> A subscripted element (e.g. a[4] -> {"value": "a", "contents": "4"})
        ast.Tuple -> A dictionary with "value":"tuple" and "content":(the annotated types taken from the tuple elements)
        ast.BinOp -> Must be "|" representing a union of multiple types. Returns a list of each of the annotated types
                     e.g. a:int|str -> ["int", "str"]
        ast.Attribute -> A string representing the composed type (e.g. a: x.y.z -> "x.y.z")

    Args:
        annotation: Annotation from the AST to be unpacked

    Returns:
        str: Name of the annotation if it has one (e.g. f() -> MyClass returns "MyClass")
        dict: Dictionary of the more complex annotation information
    """
    _logger.info("Unpacking type annotation %s", annotation)
    if isinstance(annotation, ast.Name):
        return annotation.id

    if isinstance(annotation, ast.Constant):
        return annotation.value

    if isinstance(annotation, ast.Attribute):
        return _unpack_type_annotation(annotation.value) + f".{annotation.attr}"

    if isinstance(annotation, ast.Subscript):
        return _unpack_subscript_type(annotation)

    if isinstance(annotation, ast.Tuple):
        return tuple(_unpack_type_annotation(element) for element in annotation.elts)

    if isinstance(annotation, ast.BinOp):
        left_op = _unpack_type_annotation(annotation.left)
        left_op = left_op if isinstance(left_op, list) else [left_op]
        right_op = _unpack_type_annotation(annotation.right)
        right_op = right_op if isinstance(right_op, list) else [right_op]
        return left_op + right_op

    return annotation


# --------------------------------------------------------------------------------------------------------------
def _unpack_subscript_type(subscript: ast.Subscript) -> _SubscriptDict:  # pragma: no cover    Unsupported code
    """Unpack a subscripted element from its type description

    Used for unpacking attribute tuple types, such as "float[3]".

    Args:
        subscript: Subscript element from the AST to unpack

    Returns:
        dict: Dictionary with a value in it indicating the item being subscripted (e.g. "float") and an optional
            subscript slice contents, which will always be a constant (e.g. "3")
    """
    _logger.info("Unpacking subscript %s", subscript)
    value = _unpack_type_annotation(subscript.value)
    if subscript.slice:
        slice_obj = _unpack_type_annotation(subscript.slice)
    else:
        slice_obj = None
    return {"value": value, "contents": slice_obj}


