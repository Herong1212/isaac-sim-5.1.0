def _unpack_call(call: ast.Call) -> _CallDict:  # pragma: no cover    Unsupported code
    """Unpack a function call from the AST

    Args:
        call: Function call from the AST

    Returns:
        dict: Dictionary with a fixed set of keys containing the unpacked function call information. For the
            function call `mean(1, who="grinch")` the dictionary will be populated as follows:
            **name**: *Name of the function* = "mean"
            **call_args**: *List of unpacked positional arguments* = [1]
            **call_kws**: *Dictionary of unpacked keyword arguments* = {"who": "grinch"}
    """
    _logger.info("Unpacking call %s", call)
    _logger.debug("AST --> %s", ast.dump(call, indent=2))
    func = call.func
    if isinstance(func, ast.Attribute):
        name = func.attr
    elif isinstance(func, ast.Name):
        name = func.id
    else:
        raise NotImplementedError(f"Call function {func} must be an ast.Attribute or ast.Name")

    result = {
        "name": name,
        "call_args": [_unpack_type_annotation(arg) for arg in call.args],
        "call_kws": {kw.arg: _unpack_expression(kw.value) for kw in call.keywords},
    }
    _logger.debug("Unpacked Call --> %s", result)
    return result


